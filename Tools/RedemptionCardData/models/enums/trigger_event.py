    STAR_PHASE = "star_phase"
    DRAW_PHASE = "draw_phase"
    UPKEEP = "upkeep"
    PREPARATION_PHASE = "preparation_phase"
    BATTLE_PHASE = "battle_phase"
    DISCARD_PHASE = "discard_phase"

    # Turn and battle lifecycle events (not separate REG phases)
    ON_TURN_START = "on_turn_start"
    AFTER_DRAW_PHASE = "after_draw_phase"
    AFTER_BATTLE = "after_battle"
    END_OF_TURN = "end_of_turn"

    # Active events (initiated by a player or card acting)
    ON_ATTACK = "on_attack"
    ON_BLOCK = "on_block"
    ON_PRESENT = "on_present"
    ON_TAUNT = "on_taunt"
    ON_ENTERS_BATTLE = "on_enters_battle"
    ON_BAND = "on_band"
    ON_PLAY = "on_play"
    ON_PUT_IN_PLAY = "on_put_in_play"
    ON_PUT_IN_TERRITORY = "on_put_in_territory"
    ON_PLACE = "on_place"
    ON_DRAW = "on_draw"
    ON_DISCARD = "on_discard"
    ON_BANISH = "on_banish"
    ON_BOUNCE = "on_bounce"
    ON_CAPTURE = "on_capture"
    ON_CONVERT = "on_convert"
    ON_REPENT = "on_repent"
    ON_RELEASE = "on_release"
    ON_WITHDRAW = "on_withdraw"
    ON_RESCUE_ATTEMPT = "on_rescue_attempt"
    ON_RESCUE = "on_rescue"
    ON_SUCCESSFUL_RESCUE = "on_successful_rescue"
    ON_FAILED_RESCUE = "on_failed_rescue"
    ON_SUCCESSFUL_BLOCK = "on_successful_block"
    ON_WIN_BATTLE = "on_win_battle"
    ON_LOSE_BATTLE = "on_lose_battle"
    ON_DEFEAT = "on_defeat"
    ON_MUTUAL_DESTRUCTION = "on_mutual_destruction"
    ON_END_BATTLE = "on_end_battle"
    ON_SEARCH = "on_search"
    ON_LOOK = "on_look"
    ON_REVEAL = "on_reveal"
    ON_SHUFFLE = "on_shuffle"
    ON_EXCHANGE = "on_exchange"
    ON_EQUIP = "on_equip"
    ON_RESERVE = "on_reserve"
    ON_SET_ASIDE = "on_set_aside"
    ON_UNDERDECK = "on_underdeck"
    ON_TOPDECK = "on_topdeck"
    ON_ACTIVATE = "on_activate"
    ON_ACTIVATE_ARTIFACT = "on_activate_artifact"
    ON_DEACTIVATE = "on_deactivate"

    # Passive events (something happens to a card, zone, or state)
    ON_ATTACKED = "on_attacked"
    ON_BLOCKED = "on_blocked"
    ON_BANDED = "on_banded"
    ON_PLAYED = "on_played"
    ON_PLACED = "on_placed"
    ON_DRAWN = "on_drawn"
    ON_DISCARDED = "on_discarded"
    ON_BANISHED = "on_banished"
